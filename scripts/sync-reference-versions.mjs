import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";

const require = createRequire(import.meta.url);
const root = new URL("../", import.meta.url);
const readJson = (path) => JSON.parse(readFileSync(new URL(path, root), "utf8"));
const manifests = [
  readJson("package.json"),
  readJson("apps/desktop/package.json"),
  readJson("packages/hooks/package.json"),
  readJson("packages/types/package.json"),
  readJson("packages/ui/package.json"),
];
const lock = readJson("package-lock.json");
const packageNames = new Set();
for (const manifest of manifests) {
  for (const section of ["dependencies", "devDependencies", "peerDependencies"]) {
    for (const name of Object.keys(manifest[section] ?? {})) {
      if (!name.startsWith("@project/")) packageNames.add(name);
    }
  }
}

const rows = [...packageNames]
  .sort((left, right) => left.localeCompare(right))
  .map((name) => {
    const entry = lock.packages[`node_modules/${name}`];
    if (!entry?.version) throw new Error(`No root lock entry for direct dependency ${name}`);
    return `| \`${name}\` | \`${entry.version}\` |`;
  });
const electron = require("electron");
const probe = spawnSync(electron, ["-p", "JSON.stringify(process.versions)"], {
  encoding: "utf8",
  env: { ...process.env, ELECTRON_RUN_AS_NODE: "1" },
});
if (probe.status !== 0) throw new Error(probe.stderr);
const runtime = JSON.parse(probe.stdout);
const output = `# Version snapshot

Generated from installed packages resolved by \`package-lock.json\` and the actual Electron binary.
Do not edit this file; run \`npm run docs:sync\` after dependency changes.

## Direct external packages

| Package | Resolved version |
|---|---:|
${rows.join("\n")}

## Electron runtime

| Component | Version |
|---|---:|
| Electron | \`${runtime.electron}\` |
| Chromium | \`${runtime.chrome}\` |
| Node.js | \`${runtime.node}\` |
| SQLite | \`${runtime.sqlite}\` |
| V8 | \`${runtime.v8}\` |
`;
const target = new URL("docs/reference/VERSIONS.md", root);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    console.error("docs/reference/VERSIONS.md is stale; run npm run docs:sync");
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, output);
  console.log("Updated docs/reference/VERSIONS.md from the lock-resolved installation.");
}
